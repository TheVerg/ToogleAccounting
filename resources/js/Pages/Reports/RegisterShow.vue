<script setup>
import AppLayout from '@/Layouts/AppLayout.vue';
import StatementSnapshot from '@/Components/StatementSnapshot.vue';
import { Head, Link, router } from '@inertiajs/vue3';
import { fmtDate } from '@/lib/helpers';

const props = defineProps({
    statement: Object,
    canApprove: Boolean,
});

const statusBadge = {
    draft: 'bg-amber-100 text-amber-800',
    approved: 'bg-green-100 text-green-800',
};

const approve = () => {
    if (confirm(`Approve "${props.statement.name}"? Approved statements are locked.`)) {
        router.post(`/statements/register/${props.statement.id}/approve`, {}, { preserveScroll: true });
    }
};
</script>

<template>
    <Head :title="statement.name" />
    <AppLayout>
        <template #title>{{ statement.name }}</template>
        <template #actions>
            <Link
                href="/statements/register"
                class="rounded-md border border-slate-300 bg-white px-4 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
            >← Register</Link>
            <a
                :href="`/statements/register/${statement.id}/export?format=pdf`"
                class="ml-2 rounded-md border border-slate-300 bg-white px-4 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
            >Export PDF</a>
            <a
                :href="`/statements/register/${statement.id}/export?format=csv`"
                class="ml-2 rounded-md border border-slate-300 bg-white px-4 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
            >Export Excel</a>
            <button
                v-if="statement.status === 'draft' && canApprove && !statement.deleted_at"
                class="ml-2 rounded-md bg-brand-600 px-4 py-2 text-sm font-medium text-white hover:bg-brand-700"
                @click="approve"
            >
                Approve
            </button>
        </template>

        <div class="mb-4 flex flex-wrap items-center gap-x-2 gap-y-1 text-sm text-slate-600">
            <span>{{ statement.scope_label }}</span>
            <span class="text-slate-300">·</span>
            <span>{{ statement.period_from ? fmtDate(statement.period_from) : '…' }} – {{ fmtDate(statement.period_to) }}</span>
            <span class="text-slate-300">·</span>
            <span>Generated by {{ statement.generator?.name ?? '—' }} on {{ fmtDate(statement.created_at) }}</span>
            <span class="text-slate-300">·</span>
            <span class="rounded-full px-2 py-0.5 text-xs font-medium" :class="statusBadge[statement.status]">
                {{ statement.status }}
            </span>
            <template v-if="statement.status === 'approved' && statement.approver">
                <span class="text-slate-300">·</span>
                <span>Approved by {{ statement.approver.name }} on {{ fmtDate(statement.approved_at) }}</span>
            </template>
            <span
                v-if="statement.deleted_at"
                class="rounded-full bg-red-100 px-2 py-0.5 text-xs font-semibold text-red-800"
            >DELETED</span>
        </div>

        <StatementSnapshot :statement="statement" />

        <p class="mt-3 text-xs text-slate-400">
            Frozen snapshot generated {{ fmtDate(statement.created_at) }} — figures do not change with the ledger.
        </p>
    </AppLayout>
</template>
