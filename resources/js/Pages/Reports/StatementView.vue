<script setup>
import AppLayout from '@/Layouts/AppLayout.vue';
import Modal from '@/Components/Modal.vue';
import StatementSnapshot from '@/Components/StatementSnapshot.vue';
import { Head, router, useForm } from '@inertiajs/vue3';
import { ref } from 'vue';
import { can, fmtDate } from '@/lib/helpers';

const props = defineProps({
    type: String,
    typeLabel: String,
    available: Array,
    statement: Object,
    canApprove: Boolean,
});

const statusBadge = {
    draft: 'bg-amber-100 text-amber-800',
    approved: 'bg-green-100 text-green-800',
};

const optionLabel = (a) =>
    `${a.period_from ? fmtDate(a.period_from) : '…'} – ${fmtDate(a.period_to)} · ${a.scope_label} · ${a.status}`;

const selectStatement = (event) => {
    router.get(`/statements/${props.type}`, { statement: event.target.value }, { preserveState: false });
};

const approve = () => {
    if (confirm(`Approve this ${props.typeLabel}? Approved statements are locked.`)) {
        router.post(`/statements/register/${props.statement.id}/approve`, {}, { preserveScroll: true });
    }
};

// --- Generate modal ----------------------------------------------------------
const showGenerate = ref(false);

const form = useForm({
    type: props.type,
    scope: 'current',
    from: '',
    to: new Date().toISOString().slice(0, 10),
    stay: true,
});

const submit = () =>
    form.post('/statements/register', {
        onSuccess: () => (showGenerate.value = false),
    });
</script>

<template>
    <Head :title="typeLabel" />
    <AppLayout>
        <template #title>{{ typeLabel }}</template>

        <div class="mb-4 flex flex-wrap items-end gap-3 rounded-lg bg-white p-4 shadow-sm">
            <div>
                <label class="mb-1 block text-xs uppercase tracking-wide text-gray-400">Reporting period</label>
                <select
                    class="rounded-md border-gray-300 py-1.5 text-sm"
                    :value="statement?.id"
                    @change="selectStatement"
                >
                    <option v-for="a in available" :key="a.id" :value="a.id">{{ optionLabel(a) }}</option>
                </select>
            </div>

            <div class="ml-auto flex items-center gap-2 self-center">
                <span
                    v-if="statement"
                    class="rounded-full px-2 py-0.5 text-xs font-medium"
                    :class="statusBadge[statement.status]"
                    :title="statement.status === 'approved' ? `Approved ${fmtDate(statement.approved_at)}` : ''"
                >
                    {{ statement.status }}
                </span>
                <button
                    v-if="statement && statement.status === 'draft' && canApprove"
                    class="rounded-md border border-slate-300 bg-white px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
                    @click="approve"
                >
                    Approve
                </button>
                <a
                    v-if="statement"
                    :href="`/statements/register/${statement.id}/export?format=pdf`"
                    class="rounded-md border border-slate-300 bg-white px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
                >Export PDF</a>
                <a
                    v-if="statement"
                    :href="`/statements/register/${statement.id}/export?format=csv`"
                    class="rounded-md border border-slate-300 bg-white px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"
                >Export Excel</a>
                <button
                    v-if="can('reports.view')"
                    class="rounded-md bg-brand-600 px-4 py-2 text-sm font-medium text-white hover:bg-brand-700"
                    @click="showGenerate = true"
                >
                    + Generate
                </button>
            </div>
        </div>

        <template v-if="statement">
            <div class="mb-3 text-sm text-slate-600">
                {{ statement.scope_label }} · generated by {{ statement.generator?.name ?? '—' }} {{ fmtDate(statement.created_at) }}
            </div>

            <StatementSnapshot :statement="statement" />

            <p class="mt-3 text-xs text-slate-400">
                Official registered statement — frozen at generation. Manage versions in the Statement Register.
            </p>
        </template>

        <div v-else class="rounded-xl border border-slate-200 bg-white px-6 py-16 text-center shadow-sm">
            <p class="mb-4 text-sm text-slate-500">
                No {{ typeLabel }} registered yet. Generate one for a reporting period.
            </p>
            <button
                v-if="can('reports.view')"
                class="rounded-md bg-brand-600 px-4 py-2 text-sm font-medium text-white hover:bg-brand-700"
                @click="showGenerate = true"
            >
                + Generate
            </button>
        </div>

        <Modal :show="showGenerate" @close="showGenerate = false">
            <form class="p-6" @submit.prevent="submit">
                <h2 class="mb-4 text-lg font-semibold text-gray-800">Generate {{ typeLabel }}</h2>
                <div class="grid gap-4">
                    <div>
                        <label class="mb-1 block text-sm text-gray-600">Scope</label>
                        <select v-model="form.scope" class="w-full rounded-md border-gray-300 text-sm">
                            <option value="current">Current company</option>
                            <option value="consolidated">Consolidated (all)</option>
                        </select>
                        <p v-if="form.errors.scope" class="mt-1 text-xs text-red-600">{{ form.errors.scope }}</p>
                    </div>
                    <div>
                        <label class="mb-1 block text-sm text-gray-600">From (optional)</label>
                        <input v-model="form.from" type="date" class="w-full rounded-md border-gray-300 text-sm" />
                        <p v-if="form.errors.from" class="mt-1 text-xs text-red-600">{{ form.errors.from }}</p>
                    </div>
                    <div>
                        <label class="mb-1 block text-sm text-gray-600">To</label>
                        <input v-model="form.to" type="date" class="w-full rounded-md border-gray-300 text-sm" required />
                        <p v-if="form.errors.to" class="mt-1 text-xs text-red-600">{{ form.errors.to }}</p>
                    </div>
                </div>
                <div class="mt-6 flex justify-end gap-3">
                    <button type="button" class="rounded-md border border-gray-300 px-4 py-2 text-sm" @click="showGenerate = false">Cancel</button>
                    <button type="submit" :disabled="form.processing" class="rounded-md bg-brand-600 px-4 py-2 text-sm font-medium text-white hover:bg-brand-700">
                        Generate
                    </button>
                </div>
            </form>
        </Modal>
    </AppLayout>
</template>
